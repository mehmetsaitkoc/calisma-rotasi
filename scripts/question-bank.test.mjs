const series=B.assembleSeries([bp,{...bp,id:'second'}],all);assert.equal(series.status,'ready');assert.equal(new Set(series.exams.flatMap(e=>e.questions.map(q=>q.id))).size,4,'Different variants cannot recycle the same questions');
const shortage=B.assembleSeries([bp,bp],ready.questions);assert.equal(shortage.status,'needs-content');assert.ok(shortage.exams.every(e=>e.questions.length===0));
